// Package covergate is the statement-coverage gate over the root
// module's own code: the code this project writes and is answerable
// for. Generated output, the ported third-party sources, and the
// example and fixture programs are out of scope, because a figure that
// includes them measures vendoring decisions rather than test
// discipline.
//
// Why this parses the coverage profile itself rather than calling
// `go tool cover -func`: that tool silently drops coverage blocks that
// live inside function literals assigned to package-level vars. The
// parser-combinator style in internal/parser is built out of exactly
// that shape, and the omission undercounts the module by roughly eight
// percentage points — 51.8% reported against a true 59.4% on one and
// the same profile. A gate that reports the wrong number is worse than
// no gate, so the profile is read directly; its text format is
// documented and stable.
//
// The gate is env-gated (GHTMX_COVERAGE_GATE=1) because it needs a
// profile that only a full `go test ./... -coverprofile` run produces.
// The dedicated CI job produces one, then evaluates it. The unit tests
// below are not gated: they run in every build, so the gate's own
// arithmetic cannot rot.
package covergate

import (
	"bufio"
	"fmt"
	"io"
	"os"
	"path"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
	"testing"
)

// coverageFloor is the statement coverage the project commits to for
// its own code. It is a compile-time constant on purpose: an
// environment override would let any workflow, or any contributor's
// shell, quietly disarm the gate, whereas lowering this number is a
// diff a reviewer sees. The floor only ever ratchets up — never lower
// it to turn a red build green.
const coverageFloor = 90.0

// modulePrefix is what the profile carries in front of every
// repo-relative path: a coverage profile names files by import path,
// not by filesystem path, so every root-module entry begins here.
const modulePrefix = "github.com/go-monolith/ghtmx/"

// minTrackedStatements is a tripwire against measuring a truncated or
// stale profile. A single-package run is a few hundred statements and
// would otherwise report a plausible-looking percentage over almost
// nothing. Set well below the real in-scope total so that ordinary
// scope changes — retiring a package, adding an exclusion — do not trip
// it; only a profile that is obviously not a full run does.
const minTrackedStatements = 8000

// worstPackages caps the failure report: enough to show where the
// coverage actually is, short enough to read in a CI log.
const worstPackages = 25

// block is one coverage block: a contiguous run of statements with a
// single entry and exit. numStmt is counted once no matter how many
// test binaries reported the block; covered is the OR across all of
// them.
type block struct {
	file    string // repo-relative, slash-separated
	numStmt int
	covered bool
}

// moduleRoot returns the absolute path of the repository root. The
// gate runs with the package directory as its working directory, so
// relative paths must resolve against this, never against the process
// working directory.
func moduleRoot(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot locate the covergate source file")
	}
	// file = <repo>/internal/covergate/covergate_test.go
	return filepath.Dir(filepath.Dir(filepath.Dir(file)))
}

// profilePath resolves the coverage profile to read.
// GHTMX_COVER_PROFILE relocates it; a relative value resolves against
// the repository root, because `go test ./internal/covergate/` runs
// with the package directory as its working directory.
func profilePath(root string) string {
	p := os.Getenv("GHTMX_COVER_PROFILE")
	if p == "" {
		return filepath.Join(root, "cover.out")
	}
	if filepath.IsAbs(p) {
		return p
	}
	return filepath.Join(root, p)
}

// exclusionRules are the paths outside the gate's scope, each naming
// the reason, which the report prints — so a contributor wondering why
// a package is missing from the figure gets the answer from the gate
// rather than from this file.
//
// Patterns are matched against a slash-separated, repo-relative path
// with plain string operations, never with path/filepath. A coverage
// profile always uses forward slashes because its file fields are
// import paths; on Windows filepath treats the backslash as the
// separator, and filepath.Match would silently match nothing — turning
// every exclusion into a no-op and the gate into a wrong-number
// generator that still passes.
var exclusionRules = []struct {
	name  string
	match func(path string) bool
}{
	{
		// Emitted by `ghtmx generate` and carrying the
		// "// Code generated by ghtmx - DO NOT EDIT." header. Its
		// correctness is gated by internal/corpusgate (compile + vet)
		// and by the conformance suite, not by line coverage of the
		// emitted code.
		name:  "generated output (*_ghtmx.go)",
		match: func(p string) bool { return strings.HasSuffix(p, "_ghtmx.go") },
	},
	{
		// Ported from the Go Language Server project; see NOTICE.
		// Ported code is kept as close to upstream as possible, so
		// writing tests against it to satisfy a local threshold would
		// work against that.
		name:  "ported third party (internal/lsp)",
		match: func(p string) bool { return strings.HasPrefix(p, "internal/lsp/") },
	},
	{
		// Adapted from github.com/google/safehtml; same reasoning as
		// internal/lsp. See NOTICE.
		name:  "ported third party (internal/safehtml)",
		match: func(p string) bool { return strings.HasPrefix(p, "internal/safehtml/") },
	},
	{
		// Example applications are documentation. They are compiled
		// and vetted by internal/corpusgate and embedded in the docs
		// site, which is the correctness bar that fits them.
		name:  "example application (examples/)",
		match: func(p string) bool { return strings.HasPrefix(p, "examples/") },
	},
	{
		// Fixtures exist to be built and rendered by other tests: they
		// are test input, not code under test.
		name: "test fixture (fixture/)",
		match: func(p string) bool {
			return strings.HasPrefix(p, "fixture/") || strings.Contains(p, "/fixture/")
		},
	},
	{
		// Same as fixtures: a program a test compiles and runs.
		name: "test program (testprogram/)",
		match: func(p string) bool {
			return strings.HasPrefix(p, "testprogram/") || strings.Contains(p, "/testprogram/")
		},
	},
}

// excluded reports whether a repo-relative path is outside the gate's
// scope, and names the rule that removed it.
func excluded(p string) (string, bool) {
	for _, rule := range exclusionRules {
		if rule.match(p) {
			return rule.name, true
		}
	}
	return "", false
}

// parseProfile reads a Go coverage profile and returns the distinct
// coverage blocks, keyed by position.
//
// Two properties of the input drive the whole function. First, the
// format: an optional "mode:" header, then lines of
//
//	<import path>/<file>.go:<line>.<col>,<line>.<col> <numStmt> <count>
//
// Second, and less obviously: with -coverpkg=./... every test binary
// instruments every package, so each binary emits its own copy of
// every block — 1,317,627 lines for 11,974 distinct blocks in this
// repository. Summing lines as they arrive multiplies the statement
// total by the number of test binaries and produces arithmetic that
// means nothing. Merging by position is therefore not an optimisation
// but the correctness requirement: statements count once, and a block
// counts as covered when any binary reached it.
func parseProfile(r io.Reader) (map[string]*block, error) {
	blocks := make(map[string]*block, 32768)
	scanner := bufio.NewScanner(r)
	lineNo := 0
	for scanner.Scan() {
		lineNo++
		text := scanner.Text()
		if text == "" || strings.HasPrefix(text, "mode:") {
			continue
		}
		fields := strings.Fields(text)
		if len(fields) != 3 {
			return nil, fmt.Errorf("line %d: want 3 fields, got %d: %q", lineNo, len(fields), text)
		}
		// The position separator is the last colon: an import path or
		// a Windows drive letter can contain earlier ones.
		colon := strings.LastIndex(fields[0], ":")
		if colon <= 0 {
			return nil, fmt.Errorf("line %d: no position separator in %q", lineNo, fields[0])
		}
		numStmt, err := strconv.Atoi(fields[1])
		if err != nil {
			return nil, fmt.Errorf("line %d: bad statement count %q: %w", lineNo, fields[1], err)
		}
		count, err := strconv.ParseInt(fields[2], 10, 64)
		if err != nil {
			return nil, fmt.Errorf("line %d: bad execution count %q: %w", lineNo, fields[2], err)
		}

		key := fields[0]
		b := blocks[key]
		if b == nil {
			b = &block{
				file:    strings.TrimPrefix(fields[0][:colon], modulePrefix),
				numStmt: numStmt,
			}
			blocks[key] = b
		} else if b.numStmt != numStmt {
			// Same position, different statement count: the profile
			// mixes two builds of the same file, and any total computed
			// from it would be a fiction.
			return nil, fmt.Errorf("line %d: block %s reported with %d and %d statements — the profile mixes two builds",
				lineNo, key, b.numStmt, numStmt)
		}
		if count > 0 {
			b.covered = true
		}
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if lineNo == 0 {
		return nil, fmt.Errorf("the profile is empty")
	}
	return blocks, nil
}

// pkgStat is one package's in-scope statement totals.
type pkgStat struct {
	pkg     string
	total   int
	covered int
}

func (p pkgStat) percent() float64 {
	if p.total == 0 {
		return 100
	}
	return 100 * float64(p.covered) / float64(p.total)
}

// summarize splits the blocks into in-scope and excluded, and rolls the
// in-scope ones up per package — the package being the directory of the
// file, which is what a contributor navigates to.
func summarize(blocks map[string]*block) (stats []pkgStat, total, covered int, byRule map[string]int) {
	perPkg := map[string]*pkgStat{}
	byRule = map[string]int{}
	for _, b := range blocks {
		if rule, skip := excluded(b.file); skip {
			byRule[rule] += b.numStmt
			continue
		}
		pkg := path.Dir(b.file)
		if pkg == "." {
			pkg = "(root package)"
		}
		s := perPkg[pkg]
		if s == nil {
			s = &pkgStat{pkg: pkg}
			perPkg[pkg] = s
		}
		s.total += b.numStmt
		total += b.numStmt
		if b.covered {
			s.covered += b.numStmt
			covered += b.numStmt
		}
	}
	stats = make([]pkgStat, 0, len(perPkg))
	for _, s := range perPkg {
		stats = append(stats, *s)
	}
	// Worst first by uncovered statements rather than by percentage:
	// that is the ordering that answers "where does the next hour of
	// test writing pay off most".
	sort.Slice(stats, func(i, j int) bool {
		gi, gj := stats[i].total-stats[i].covered, stats[j].total-stats[j].covered
		if gi != gj {
			return gi > gj
		}
		return stats[i].pkg < stats[j].pkg
	})
	return stats, total, covered, byRule
}

// report writes the per-package table, so a failing build names the
// packages responsible instead of only the aggregate.
func report(w io.Writer, stats []pkgStat, total, covered int, byRule map[string]int) {
	fmt.Fprintf(w, "\nown-code statement coverage: %.2f%% (%d/%d statements, %d packages)\n",
		100*float64(covered)/float64(total), covered, total, len(stats))

	fmt.Fprintln(w, "\nout of scope (statements excluded from the figure above):")
	for _, rule := range exclusionRules {
		if n, matched := byRule[rule.name]; matched {
			fmt.Fprintf(w, "  %8d  %s\n", n, rule.name)
		} else {
			// Informational, never fatal: several rules are defensive.
			// The fixture and testprogram rules legitimately match
			// nothing in some profiles.
			fmt.Fprintf(w, "  %8s  %s (matched nothing in this profile)\n", "-", rule.name)
		}
	}

	shown := stats
	if len(shown) > worstPackages {
		shown = shown[:worstPackages]
	}
	fmt.Fprintf(w, "\nleast-covered packages (%d of %d shown, most uncovered statements first):\n",
		len(shown), len(stats))
	fmt.Fprintf(w, "  %7s  %6s  %-11s  %s\n", "MISSING", "COVER", "STMTS", "PACKAGE")
	for _, s := range shown {
		fmt.Fprintf(w, "  %7d  %5.1f%%  %5d/%-5d  %s\n",
			s.total-s.covered, s.percent(), s.covered, s.total, s.pkg)
	}
}

// TestOwnCodeCoverageMeetsTheFloor is the gate: statement coverage of
// the root module's own code must not fall below coverageFloor.
//
// It reads a profile produced by a preceding
//
//	go test ./... -covermode=atomic -coverpkg=./... -coverprofile=cover.out -timeout 20m
//
// and is skipped without GHTMX_COVERAGE_GATE=1 precisely so that this
// run — which includes this package — does not try to read the file it
// is in the middle of writing.
func TestOwnCodeCoverageMeetsTheFloor(t *testing.T) {
	if os.Getenv("GHTMX_COVERAGE_GATE") == "" {
		t.Skip("set GHTMX_COVERAGE_GATE=1 to run the coverage gate (needs a cover.out from a full `go test ./... -coverprofile` run)")
	}
	profile := profilePath(moduleRoot(t))

	f, err := os.Open(profile)
	if err != nil {
		t.Fatalf("cannot read the coverage profile at %s: %v\n\nproduce one with:\n  go test ./... -covermode=atomic -coverpkg=./... -coverprofile=cover.out -timeout 20m",
			profile, err)
	}
	defer f.Close()

	blocks, err := parseProfile(bufio.NewReaderSize(f, 1<<20))
	if err != nil {
		t.Fatalf("cannot parse %s: %v", profile, err)
	}

	stats, total, covered, byRule := summarize(blocks)
	if total < minTrackedStatements {
		t.Fatalf("only %d in-scope statements in %s — a full `go test ./... -coverpkg=./...` run reports far more, so this profile is truncated or stale",
			total, profile)
	}

	report(os.Stdout, stats, total, covered, byRule)

	percent := 100 * float64(covered) / float64(total)
	if percent+1e-9 < coverageFloor {
		t.Errorf("own-code coverage %.2f%% is below the %.2f%% floor: %d of %d in-scope statements are untested.\n"+
			"Add tests for the packages listed above. Lowering coverageFloor is not the fix — it only ratchets up.",
			percent, coverageFloor, total-covered, total)
		return
	}
	t.Logf("own-code coverage %.2f%% clears the %.2f%% floor", percent, coverageFloor)
}

// TestProfileParsingMergesDuplicateBlocks pins the two properties the
// aggregate depends on, against a synthetic profile shaped like a real
// -coverpkg run: the same block is emitted once per test binary, and
// one binary covering it is enough.
func TestProfileParsingMergesDuplicateBlocks(t *testing.T) {
	const profile = `mode: atomic
github.com/go-monolith/ghtmx/internal/parser/a.go:10.20,12.3 2 0
github.com/go-monolith/ghtmx/internal/parser/a.go:10.20,12.3 2 7
github.com/go-monolith/ghtmx/internal/parser/a.go:10.20,12.3 2 0
github.com/go-monolith/ghtmx/internal/parser/a.go:14.2,15.4 3 0
github.com/go-monolith/ghtmx/runtime.go:5.1,6.2 1 1
github.com/go-monolith/ghtmx/internal/lsp/x.go:1.1,9.9 40 0
github.com/go-monolith/ghtmx/examples/crud/main.go:1.1,9.9 30 0
github.com/go-monolith/ghtmx/conformance/conformance_ghtmx.go:1.1,9.9 50 50
`
	blocks, err := parseProfile(strings.NewReader(profile))
	if err != nil {
		t.Fatal(err)
	}
	if len(blocks) != 6 {
		t.Fatalf("got %d distinct blocks, want 6 — duplicates were not merged by position", len(blocks))
	}

	stats, total, covered, byRule := summarize(blocks)
	// In scope: 2+3 from internal/parser, 1 from the root package.
	if total != 6 {
		t.Errorf("in-scope statements = %d, want 6 (duplicate blocks counted more than once?)", total)
	}
	if covered != 3 {
		t.Errorf("covered statements = %d, want 3 — a block is covered when any test binary reached it", covered)
	}
	for _, tt := range []struct {
		rule string
		want int
	}{
		{"ported third party (internal/lsp)", 40},
		{"example application (examples/)", 30},
		// Covered generated code must not inflate the figure either.
		{"generated output (*_ghtmx.go)", 50},
	} {
		if got := byRule[tt.rule]; got != tt.want {
			t.Errorf("%s excluded %d statements, want %d", tt.rule, got, tt.want)
		}
	}
	if len(stats) != 2 || stats[0].pkg != "internal/parser" {
		t.Errorf("package rollup = %+v, want internal/parser worst of two packages", stats)
	}
}

// TestProfileParsingRejectsMalformedInput pins the failure modes that
// would otherwise produce a confident wrong number.
func TestProfileParsingRejectsMalformedInput(t *testing.T) {
	tests := []struct {
		name    string
		profile string
	}{
		{"empty", ""},
		{"wrong field count", "mode: atomic\ngithub.com/go-monolith/ghtmx/a.go:1.1,2.2 3\n"},
		{"no position separator", "mode: atomic\ngithub.com/go-monolith/ghtmx/a.go 3 1\n"},
		{"bad statement count", "mode: atomic\ngithub.com/go-monolith/ghtmx/a.go:1.1,2.2 x 1\n"},
		{"bad execution count", "mode: atomic\ngithub.com/go-monolith/ghtmx/a.go:1.1,2.2 3 x\n"},
		{
			"mixed builds",
			"mode: atomic\n" +
				"github.com/go-monolith/ghtmx/a.go:1.1,2.2 3 1\n" +
				"github.com/go-monolith/ghtmx/a.go:1.1,2.2 4 1\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := parseProfile(strings.NewReader(tt.profile)); err == nil {
				t.Error("parseProfile accepted a malformed profile, want an error")
			}
		})
	}
}

// TestExclusionRules pins the scope decision itself, including the
// cases that are easy to get wrong: a root-level file, a nested
// fixture, and the near-misses that must stay in scope.
func TestExclusionRules(t *testing.T) {
	tests := []struct {
		path string
		want bool
	}{
		{"runtime.go", false},
		{"internal/parser/parser.go", false},
		{"cmd/ghtmx/generatecmd/main.go", false},
		{"conformance/conformance.go", false},
		{"benchmarks/corpus/corpus.go", false},

		{"conformance/conformance_ghtmx.go", true},
		{"ghtmxgen/routes_ghtmx.go", true},
		{"internal/lsp/protocol/tsserver.go", true},
		{"internal/safehtml/style.go", true},
		{"examples/crud/cmd/main.go", true},
		{"internal/wasmcheck/fixture/main.go", true},
		{"cmd/ghtmx/generatecmd/run/testprogram/main.go", true},

		// Near-misses that must stay in scope: a prefix match on the
		// bare word would wrongly drop all of these.
		{"internal/lspdiag/diag.go", false},
		{"internal/safehtmlutil/util.go", false},
		{"internal/fixtures/load.go", false},
		{"cmd/ghtmx/ghtmx.go", false},
	}
	for _, tt := range tests {
		t.Run(tt.path, func(t *testing.T) {
			if _, got := excluded(tt.path); got != tt.want {
				t.Errorf("excluded(%q) = %v, want %v", tt.path, got, tt.want)
			}
		})
	}
}
